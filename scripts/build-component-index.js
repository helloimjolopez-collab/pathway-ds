/**
 * build-component-index.js, generate the component index from the manifest.
 *
 * WHY THIS EXISTS. A reader arriving at this repo, human or agent, had no list
 * of what is in it. README.md is entirely about tokens and never names a
 * component; the Storybook Welcome page named eight components by hand and had
 * not been touched when Widget, KPI Tile and Dashboard landed, so it was
 * actively misleading about what the library contains. A hand-written list of
 * fourteen components across two files is two things to forget to update, and
 * both had already been forgotten.
 *
 * So the index is generated from components/manifest.json, which is the
 * registry CLAUDE.md §10.5 already requires every component to be in, and
 * written between markers in README.md and src/stories/Welcome.mdx. Run with
 * --check to fail when either file is stale; that is what CI uses, so a new
 * component cannot ship without appearing in both places.
 *
 * It deliberately does NOT invent any content. Every cell comes from the
 * manifest or from a file existing on disk. A component with no spec shows as
 * having no spec rather than as having one somewhere unstated.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const ROOT = path.join(__dirname, "..");
const MANIFEST = path.join(ROOT, "components/manifest.json");
// MDX IS NOT MARKDOWN HERE: an HTML comment is a parse error in it, not a
// comment. `<!-- BEGIN ... -->` in Welcome.mdx failed the Storybook index with
// "Unexpected character `!` (U+0021) before name", which blanks the whole page.
// So each format gets its own comment syntax.
const MARKERS = {
  md: {
    begin: "<!-- BEGIN component-index (generated by scripts/build-component-index.js) -->",
    end: "<!-- END component-index -->",
  },
  mdx: {
    begin: "{/* BEGIN component-index (generated by scripts/build-component-index.js) */}",
    end: "{/* END component-index */}",
  },
};
const markersFor = (file) => (file.endsWith(".mdx") ? MARKERS.mdx : MARKERS.md);

const exists = (p) => p && fs.existsSync(path.join(ROOT, p));

/**
 * Storybook docs id, from the `title` on the stories file's DEFAULT EXPORT.
 *
 * It must be anchored to `export default`, not to the first `title:` in the
 * file. Several stories files carry sample data with its own `title` field
 * above the meta, so an unanchored match gave Dashboard the id
 * `financial-kpis` and NavShell the id `teams`, both of which 404.
 */
function storybookId(storiesPath) {
  if (!exists(storiesPath)) return null;
  const src = fs.readFileSync(path.join(ROOT, storiesPath), "utf8");
  const meta = src.slice(src.indexOf("export default"));
  const m = meta.match(/title:\s*["']([^"']+)["']/);
  if (!m) return null;
  return m[1].toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function load() {
  const { components } = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  return Object.entries(components).map(([key, c]) => {
    // A `module` that is not a module is a manifest bug, not something to
    // print: nav-shell's pointed at its own spec.
    const modules = (c.modules || (c.module ? [c.module] : []))
      .filter((m) => /\.(jsx?|tsx?|mjs)$/.test(m));
    const fg = c.figma || {};
    return {
      key,
      name: c.displayName || key,
      internal: !!c.internal,
      repoOnly: !!c.repoOnly,
      spec: exists(c.spec) ? c.spec : null,
      modules: modules.filter(exists),
      stories: exists(c.stories) ? c.stories : null,
      sbId: storybookId(c.stories),
      html: exists(`components/${key}/${key}.html`) ? `components/${key}/${key}.html` : null,
      node: fg.nodeId || null,
      // KPI Tile is a family of sets on one page rather than one set, so it has
      // `sets` and no single nodeId. Reporting "no Figma component" for it was
      // wrong: it has seven.
      sets: fg.sets ? Object.keys(fg.sets).length : 0,
      page: fg.page || null,
      fileKey: fg.fileKey || null,
      codeConnect: (c.codeConnect || []).filter(exists).length,
    };
  });
}

/** The README table: paths, because a reader there is in the filesystem. */
function readmeTable(rows) {
  const line = (r) => {
    const place = r.repoOnly
      ? "repo only, not in Figma"
      : r.node
        ? `\`${r.node}\``
        : r.sets
          ? `${r.sets} sets on page \`${r.page}\``
          : "no Figma component";
    const sb = r.sbId ? `[open](https://helloimjolopez-collab.github.io/pathway-ds/storybook/?path=/docs/${r.sbId}--docs)` : (r.internal ? "nested only" : "none");
    return `| **${r.name}** | ${r.spec ? `[spec](${r.spec})` : "none"} | ${r.modules.map((m) => `[\`${path.basename(m)}\`](${m})`).join("<br>") || (r.internal ? "in its parent" : "composed, see its stories")} | ${sb} | ${place} | ${r.codeConnect || "0"} |`;
  };
  const pages = rows.filter((r) => !r.internal);
  const blocks = rows.filter((r) => r.internal);
  const head = [
    "| Component | Spec | Module | Storybook | Figma node | Code Connect files |",
    "|---|---|---|---|---|---|",
  ];
  const out = [
    `**${pages.length} components with their own page, ${blocks.length} building blocks that only exist nested.**`,
    "",
    ...head,
    ...pages.map(line),
  ];
  if (blocks.length) {
    out.push(
      "",
      "Building blocks. Each is mapped for Code Connect and specced, but has no page",
      "of its own because it only ever appears as a nested instance inside the",
      "component above it.",
      "",
      ...head,
      ...blocks.map(line),
    );
  }
  return out.join("\n");
}

/** The Welcome table: Storybook links, because a reader there is in Storybook. */
function welcomeTable(rows) {
  const pages = rows.filter((r) => !r.internal && r.sbId);
  return [
    "| Component | What it is | Open it |",
    "|---|---|---|",
    ...pages.map((r) => {
      const blurb = {
        widget: "The dashboard container. Size is depth, not scale.",
        "kpi-tile": "The KPI card, three shapes, and the building block it nests.",
        dashboard: "The board, its toolbar, and the add-widget flow.",
        "top-nav": "The top bar: module switcher, org switcher, search, actions, avatar.",
        sidenav: "The left rail, expanded and collapsed.",
        "nav-shell": "TopNav plus SideNav plus a page, assembled.",
        button: "Three styles, four types, four sizes.",
        checkbox: "Every state, including the highlight swap.",
        search: "The TopNav search bar and its full-bar takeover.",
        "org-switcher": "The org trigger and its panel.",
        spinner: "The indeterminate indicator.",
        scrollbar: "The custom scrollbar. Repo only, no Figma component.",
      }[r.key] || "";
      return `| **${r.name}** | ${blurb} | [Open](?path=/docs/${r.sbId}--docs) |`;
    }),
  ].join("\n");
}

function inject(file, body, label) {
  const p = path.join(ROOT, file);
  const src = fs.readFileSync(p, "utf8");
  const { begin, end } = markersFor(file);
  const i = src.indexOf(begin);
  const j = src.indexOf(end);
  if (i === -1 || j === -1) {
    throw new Error(`${file} has no ${begin} / ${end} markers. Add them first.`);
  }
  const next = src.slice(0, i) + begin + "\n\n" + body + "\n\n" + src.slice(j);
  return { p, src, next, label };
}

/**
 * Verify every generated Storybook id against a build, when one is present.
 *
 * An id is derived from the meta `title`, so a renamed title silently turns
 * every link in this index into a 404 while the table still looks right. The
 * index.json a build emits is the only thing that knows the real ids.
 */
function verifyAgainstBuild(rows) {
  const idx = path.join(ROOT, "storybook-static/index.json");
  if (!fs.existsSync(idx)) {
    console.log("  (no storybook-static/index.json, skipping link verification)");
    return 0;
  }
  const entries = JSON.parse(fs.readFileSync(idx, "utf8")).entries || {};
  const docs = new Set(Object.keys(entries).filter((k) => entries[k].type === "docs"));
  const prefixes = new Set(Object.keys(entries).map((k) => k.split("--")[0]));
  let broken = 0;
  for (const r of rows) {
    if (!r.sbId) continue;
    if (docs.has(`${r.sbId}--docs`) || prefixes.has(r.sbId)) continue;
    console.error(`  BROKEN LINK  ${r.name}: ${r.sbId} is not in the build`);
    broken++;
  }
  if (!broken) console.log("  every Storybook link in the index resolves");
  return broken;
}

function main() {
  const check = process.argv.includes("--check");
  const rows = load();
  const broken = verifyAgainstBuild(rows);
  const targets = [
    inject("README.md", readmeTable(rows), "README.md"),
    inject("src/stories/Welcome.mdx", welcomeTable(rows), "Welcome.mdx"),
  ];
  let stale = 0;
  for (const t of targets) {
    if (t.src === t.next) {
      console.log(`  up to date  ${t.label}`);
      continue;
    }
    stale++;
    if (check) {
      console.error(`  STALE       ${t.label}`);
    } else {
      fs.writeFileSync(t.p, t.next);
      console.log(`  written     ${t.label}`);
    }
  }
  if (broken) {
    console.error(`\n${broken} Storybook link(s) in the index do not resolve.`);
    process.exit(1);
  }
  if (check && stale) {
    console.error(`\n${stale} file(s) out of step with components/manifest.json.`);
    console.error("Run: npm run build-component-index");
    process.exit(1);
  }
  console.log(`\n${rows.length} components indexed.`);
}

main();
